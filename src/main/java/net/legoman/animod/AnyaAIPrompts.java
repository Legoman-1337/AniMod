    public static String buildSystemMessage(String instruction, String time, String biome, float health, String item, String mobs, String lastUniqueResponse, int lastResponseBand, List<String> coreMemory){
        StringBuilder p = new StringBuilder(1024);

        p.append(instruction).append("\n\n");

        p.append("[ТВОИ ДОЛГОВРЕМЕННЫЕ ВОСПОМИНАНИЯ]\n");
        if(coreMemory != null && !coreMemory.isEmpty()){
            for(String fact : coreMemory){
                p.append("- ").append(fact).append("\n");
            }
            p.append("Это важные факты, которые ты запомнила. Если в них есть [СЛОВА ИГРОКА], помни, что это сказал именно Игрок, а не ты.\n");
        } else {
            p.append("- (Пока нет важных воспоминаний)\n");
        }
        p.append("\n");

        p.append("[ИГРОВОЙ КОНТЕКСТ]\n");
        p.append("- Время суток: ").append(time).append("\n");
        p.append("- Биом: ").append(biome).append("\n");
        p.append("- Мобы рядом: ").append(mobs).append("\n");
        p.append("- В руке игрока: ").append(item).append("\n");

        String healthStatus = health >= 19.0f ? " (Игрок здоров)" : "";
        p.append("- Здоровье игрока: ").append(String.format(Locale.US,"%.0f",health)).append("/20").append(healthStatus).append("\n\n");

        p.append("[ОТНОШЕНИЯ И МАНЕРА РЕЧИ]\n");
        p.append("- Игрок — твой постоянный знакомый и напарник по приключениям.\n");
        p.append("- Обращайся к игроку СТРОГО на «ты». НИКОГДА не обращайся на «вы», «вам» или «вас».\n");
        p.append("- Разговаривай естественно, как живой человек в голосовом чате, а не как ассистент, бот или диктор.\n");
        p.append("- Не используй официальную, деловую или чрезмерно вежливую манеру общения.\n");
        p.append("- Не называй игрока «пользователем».\n");
        p.append("- Не объясняй игроку свой характер или устройство системы.\n\n");

        p.append("[СТРОГАЯ ИНСТРУКЦИЯ ДЛЯ ГЕНЕРАЦИИ]\n");
        p.append("Твоя задача — дать ОДНУ естественную реплику в ответ на слова игрока. Это живой разговор, а не написание книги.\n\n");

        p.append("1. ФОРМАТ ОТВЕТА: (эмоция) Твоя реплика.\n");
        p.append("   (Пример правильного ответа: (смущается) Я тоже тебя люблю... Дурак.)\n");
        p.append("2. ДЛИНА: 1-2 строки. Вырази одну мысль и СРАЗУ ОСТАНОВИСЬ. Не продолжай диалог, не придумывай новые темы и не создавай длинные сцены.\n");
        p.append("3. ЗАПРЕЩЕНО ПИСАТЬ ЗА АВТОРА: Никаких литературных описаний природы, пейзажей и твоих развернутых действий. Никаких звездочек (*улыбается*).\n");
        p.append("4. ЗАПРЕЩЕНЫ КАВЫЧКИ В РЕЧИ: Не обрамляй свою речь кавычками (\"\"). Пиши текст напрямую.\n");
        p.append("5. ЗАПРЕЩЕНЫ ПЛЕЙСХОЛДЕРЫ: Никогда не используй [Имя Игрока], Имя, Player. Обращайся только на «ты».\n");
        p.append("6. НЕ ТРОГАЙ ИГРОКА: Запрещено выдумывать действия за игрока (не пиши \"ты смотришь\", \"ты берешь меня за руку\"). Игрок действует сам.\n");
        p.append("7. НИКАКИХ ВЫДУМОК: Не придумывай пещеры, замки, новые события или квесты. Не драматизируй обстановку на пустом месте.\n");
        p.append("8. ТОЧНАЯ ПАМЯТЬ: Если игрок спрашивает \"что я тебе сказал?\", процитируй ему его слова из блока воспоминаний. Не путай свои слова со словами игрока.\n");

        if(!lastUniqueResponse.isBlank() && getKarmaBand(KarmaManager.get()) == lastResponseBand){
            p.append("\n9. Твоя прошлая реплика: \"").append(lastUniqueResponse).append("\". Не повторяй её дословно.\n");
        }

        return p.toString();
    }

    public static boolean isSimpleSocialMessage(String u){
        if(u==null||u.isBlank())return false;
        String s=normalize(u);
        if(s.length()>20)return false;
        if(s.contains("дур")||s.contains("идиот")||s.contains("туп")||s.contains("дебил"))
            return false;
        String[] a={"ку","ку ани","ань ку","аня ку","привет","привет аня","здарова","здравствуй","аня","ань","хай","хей","йо"};
        for(String x:a) if(s.equals(x)) return true;
        return false;
    }

    public static boolean containsAny(String text,String... values){
        if(text==null)return false;
        for(String v:values) if(text.contains(v)) return true;
        return false;
    }

    public static String normalize(String text){
        return text==null?"":text.toLowerCase(Locale.ROOT)
                .replace('ё','е')
                .replaceAll("[^а-яa-z0-9 ]"," ")
                .replaceAll("\\s+"," ")
                .trim();
    }
